def decision_text(action: str, prev: str, new: str, prev_o: str, new_o: str) -> str:
    if action == "引き上げ":
        return f"以上を踏まえ、発行体格付を{prev}から{new}に引き上げた。方向性は{new_o}とした。"
    if action == "引き下げ":
        return f"以上を踏まえ、発行体格付を{prev}から{new}に引き下げた。方向性は{new_o}とした。"
    if action == "方向性変更":
        return f"以上を踏まえ、発行体格付{new}を維持し、方向性を{prev_o}から{new_o}に変更した。"
    return f"以上を踏まえ、発行体格付{new}（{new_o}）を据え置いた。"


def build_report_rows() -> list[list]:
    rng = random.Random(2025)
    issuers = []
    used = set()
    while len(issuers) < N_REPORT_ISSUERS:
        industry = rng.choice(INDUSTRY_LIST)
        dept, center, suffixes, _ = INDUSTRIES[industry]
        cdex = rng.choice(PREFIXES) + rng.choice(suffixes)
        if cdex in used:
            continue
        used.add(cdex)
        form = rng.choice(SUFFIX_FORM)
        biz = f"{cdex}{form}" if form == "ホールディングス" else f"{cdex}株式会社"
        n = len(issuers) + 1
        pos = min(max(center + rng.choice([-2, -1, 0, 0, 1, 2]), 0), len(SCALE) - 1)
        issuers.append(dict(iid=f"R{n:04d}", code=f"{2000 + n}", sec=str(4000 + n * 7), cdex=cdex, biz=biz,
                            industry=industry, dept=dept, pos=pos, outlook="安定的",
                            analyst=rng.choice(REPORT_ANALYSTS)))

    rows = []
    for it in issuers:
        for year in REPORT_YEARS:
            reports = [("定期見直し", None)]
            if rng.random() < 0.12:
                reports.append(("臨時見直し", None))
            for kind, _ in reports:
                prev, prev_o = SCALE[it["pos"]], it["outlook"]
                roll = rng.random()
                action = "据え置き"
                if roll < 0.10 and it["pos"] > 0:
                    action = "引き上げ"; it["pos"] -= 1; it["outlook"] = "安定的"
                elif roll < 0.20 and it["pos"] < len(SCALE) - 1:
                    action = "引き下げ"; it["pos"] += 1; it["outlook"] = "安定的"
                elif roll < 0.35:
                    action = "方向性変更"
                    it["outlook"] = rng.choice([o for o in OUTLOOK_TEXT if o != prev_o])
                if action == "据え置き" and year == REPORT_YEARS[0] and kind == "定期見直し":
                    pass
                new, new_o = SCALE[it["pos"]], it["outlook"]
                _, _, _, biz_pool = INDUSTRIES[it["industry"]]
                parts = [rng.sample(biz_pool, 2), rng.sample(FIN_SENTENCES, 2), [rng.choice(RISK_SENTENCES)]]
                if action == "引き上げ":
                    parts.insert(2, [rng.choice(UP_SENTENCES)])
                elif action == "引き下げ":
                    parts.insert(2, [rng.choice(DOWN_SENTENCES)])
                body = (
                    "【格付理由】" + "".join("".join(p) for p in parts[:1] + parts[1:])
                    + "【格付の方向性】" + OUTLOOK_TEXT[new_o]
                    + "【今回の判断】" + decision_text(action, prev, new, prev_o, new_o)
                )
                month, day = rng.randint(1, 12), rng.randint(1, 28)
                pub = f"{year}-{month:02d}-{day:02d}"
                tags = [kind] + rng.sample(REPORT_TAGS[2:], 1) + ([action] if action in ("引き上げ", "引き下げ", "方向性変更") else [])
                rows.append([
                    it["iid"], it["code"], it["sec"], year, pub, it["cdex"], it["biz"], it["industry"],
                    it["dept"], it["analyst"], pub, new, new_o, action, "・".join(tags), body,
                ])
    return rows


def write_both(out: Path, stem: str, rows: list[list]) -> None:
    with open(out / f"{stem}.csv", "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(COLUMNS)
        w.writerows(rows)
    wb = Workbook()
    ws = wb.active
    ws.append(COLUMNS)
    for r in rows:
        ws.append(r)
    wb.save(out / f"{stem}.xlsx")
    print(f"{len(rows)} rows -> {out / stem}.(csv|xlsx)")


def main() -> None:
    out = Path(__file__).parent / "data"
    out.mkdir(exist_ok=True)
    write_both(out, "sample_issuer_reports", build_rows())
    write_both(out, "sample_rating_reports", build_report_rows())

if __name__ == "__main__":
    main()
