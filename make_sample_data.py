        for year in (2022, 2023, 2024, 2025):
            action = rng.choice(ACTIONS)
            outlook = rng.choice(OUTLOOKS)
            body = (
                f"【格付理由】{BUSINESS[industry]}"
                + "".join(rng.sample(FINANCE, 2))
                + rng.choice(RISK)
                + f"【格付の見通し】{OUTLOOK_TEXT[outlook]}"
                + ACTION_REPORT[action].format(r=rating)
            )
            pub = f"{year}-{rng.randint(1, 12):02d}-{rng.randint(1, 28):02d}"
